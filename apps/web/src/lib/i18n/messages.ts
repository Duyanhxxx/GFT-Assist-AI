function getMessageValue(tree: MessageTree, key: string): MessageValue | undefined {
  return key.split(".").reduce<MessageValue | undefined>((current, segment) => {
    if (!current || typeof current === "string") {
      return undefined;
    }

    return current[segment];
  }, tree);
}

export function createTranslator(locale: Locale) {
  return (key: string, params?: Record<string, string | number>) => {
    const value = getMessageValue(messages[locale], key);
    const fallback = getMessageValue(messages.en, key);
    const template = typeof value === "string" ? value : typeof fallback === "string" ? fallback : key;

    if (!params) {
      return template;
    }

    return Object.entries(params).reduce(
      (result, [paramKey, paramValue]) => result.replaceAll(`{${paramKey}}`, String(paramValue)),
      template,
    );
  };
}
